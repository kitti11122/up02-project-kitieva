"""Расширенное тестирование алгоритма скидки (вариант 25%)."""
from datetime import datetime
from discount import calculate_price_with_discount


def print_test_report(passed, total):
    """Выводит отчёт о тестировании."""
    print("=" * 40)
    print("ОТЧЁТ О ТЕСТИРОВАНИИ")
    print(f"Пройдено: {passed} / {total}")
    if passed == total:
        print("Результат: ✅ УСПЕХ")
    else:
        print("Результат: ❌ ЕСТЬ ОШИБКИ")
    print("=" * 40)


def run_tests():
    """Прогон всех тестов."""
    # Реальные заказы в БД:
    #   id=1 — товар 1, дата 2026-09-15
    #   id=2 — товар 2, дата 2026-09-20
    #   id=3 — товар 3, дата 2026-09-25
    # Заказы есть ТОЛЬКО в сентябре 2026.

    test_cases = [
        # ---------- Базовые тесты (дата 15.10.2026, предыдущий месяц — сентябрь) ----------
        (1, 1500, datetime(2026, 10, 15), 1500, "«Война и мир» — заказ в сентябре → без скидки"),
        (2, 1200, datetime(2026, 10, 15), 1200, "«Мастер и Маргарита» — заказ в сентябре → без скидки"),
        (3, 1000, datetime(2026, 10, 15), 1000, "«Преступление и наказание» — заказ в сентябре → без скидки"),
        (4, 800,  datetime(2026, 10, 15), 600,  "«Евгений Онегин» — заказов нет → скидка 25%"),
        (5, 2000, datetime(2026, 10, 15), 1500, "«Властелин колец» — заказов нет → скидка 25%"),

        # ---------- Тесты прошлого ДЗ (разные даты) ----------
        (2, 1200, datetime(2026, 11, 15), 900,  "15.11.2026 — октябрь пуст → скидка 25%"),
        (1, 1500, datetime(2026, 11, 15), 1125, "15.11.2026 — октябрь пуст → скидка 25%"),
        (4, 800,  datetime(2026, 9, 1),   600,  "01.09.2026 — август пуст → скидка 25%"),

        # ---------- НОВЫЕ 5 ГРАНИЧНЫХ ТЕСТОВ (Задание 1) ----------

        # Граничный случай 1: дата = 1-е число месяца
        (1, 1500, datetime(2026, 12, 1), 1125,
         "01.12.2026 — 1-е число: предыдущий месяц = ноябрь (пусто) → скидка 25%"),

        # Граничный случай 2: дата = последний день месяца
        (2, 1200, datetime(2026, 12, 31), 900,
         "31.12.2026 — последний день месяца: предыдущий = ноябрь (пусто) → скидка 25%"),

        # Граничный случай 3: товар с нулевой ценой
        (6, 0, datetime(2026, 11, 15), 0,
         "Цена = 0 → 0 × 0.75 = 0 (скидка применяется, но результат 0)"),

        # Граничный случай 4: товар с отрицательным количеством
        # (алгоритм скидки зависит от заказов, а не от остатка — тест проверяет,
        #  что отрицательное количество НЕ ломает расчёт)
        (7, 500, datetime(2026, 11, 15), 375,
         "Товар 7 — quantity<0 не влияет на скидку (она зависит от заказов)"),

        # Граничный случай 5: заказы были в позапрошлом месяце, но не в предыдущем
        (2, 1200, datetime(2026, 11, 15), 900,
         "Товар 2: заказ в сентябре (позапрошлый), в октябре (предыдущий) — пусто → скидка 25%"),
    ]

    print("=" * 75)
    print("РАСШИРЕННОЕ ТЕСТИРОВАНИЕ (вариант 25% + граничные случаи)")
    print("=" * 75)

    passed = 0
    for product_id, price, date, expected, comment in test_cases:
        result = calculate_price_with_discount(product_id, price, date)
        status = "✅" if result == expected else "❌"
        if result == expected:
            passed += 1
        print(f"{status} Товар {product_id} на {date.date()}: "
              f"{price} → {result} (ожидалось {expected})")
        print(f"      {comment}")

    # Отчёт (Задание 2)
    print_test_report(passed, len(test_cases))


if __name__ == "__main__":
    run_tests()