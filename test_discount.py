"""Тестирование алгоритма скидки (вариант 25%) на данных библиотеки."""
from datetime import datetime
from discount import calculate_price_with_discount


def run_tests():
    """Прогон расширенных тестов."""
   
    test_cases = [
  
        (1, 1500, datetime(2026, 10, 15), 1500, "«Война и мир» — заказ в сентябре → без скидки"),
        (2, 1200, datetime(2026, 10, 15), 1200, "«Мастер и Маргарита» — заказ в сентябре → без скидки"),
        (3, 1000, datetime(2026, 10, 15), 1000, "«Преступление и наказание» — заказ в сентябре → без скидки"),
        (4, 800,  datetime(2026, 10, 15), 600,  "«Евгений Онегин» — заказов нет → скидка 25%"),
        (5, 2000, datetime(2026, 10, 15), 1500, "«Властелин колец» — заказов нет → скидка 25%"),

        # --- Новые тесты (разные даты) ---
        (2, 1200, datetime(2026, 11, 15), 900,  "15.11.2026 — в октябре заказов не было → скидка 25%"),
        (1, 1500, datetime(2026, 11, 15), 1125, "15.11.2026 — в октябре заказов не было → скидка 25%"),
        (4, 800,  datetime(2026, 9, 1),   600,  "01.09.2026 — в августе заказов не было → скидка 25%"),
        (5, 2000, datetime(2026, 12, 15), 1500, "15.12.2026 — в ноябре заказов не было → скидка 25%"),
        (6, 1800, datetime(2027, 1, 15),  1350, "15.01.2027 — в декабре заказов не было → скидка 25%"),
    ]

    print("=" * 75)
    print("РАСШИРЕННОЕ ТЕСТИРОВАНИЕ АЛГОРИТМА СКИДКИ (вариант 25%)")
    print("=" * 75)

    passed = 0
    for product_id, price, date, expected, comment in test_cases:
        result = calculate_price_with_discount(product_id, price, date)
        status = "✅" if result == expected else "❌"
        if result == expected:
            passed += 1
        print(f"{status} Товар {product_id} на {date.date()}: "
              f"{price} → {result} (ожидалось {expected}) — {comment}")

    print("=" * 75)
    print(f"Пройдено: {passed} / {len(test_cases)}")
    print("=" * 75)


if __name__ == "__main__":
    run_tests()